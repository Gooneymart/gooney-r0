use r0_core::WorkspaceConfig;
use std::fs;
use std::path::PathBuf;
use anyhow::Result;

pub struct DriverGenerator;

impl DriverGenerator {
    pub fn generate_template(output_dir: &PathBuf, config: &WorkspaceConfig) -> Result<()> {
        fs::create_dir_all(output_dir)?;

        let c_source = format!(
            r#"/* Auto-generated by r0-driver-gen for {} */
#include <linux/init.h>
#include <linux/module.h>
#include <linux/kernel.h>
#include <linux/fs.h>
#include <linux/io.h>
#include <linux/uaccess.h>

MODULE_LICENSE("GPL");
MODULE_AUTHOR("Gooneymart R0 DV Engine");
MODULE_DESCRIPTION("DKMS Test Harness Driver for RISC-V Soft-IP");

#define DEVICE_NAME "gooney_r0"
#define MMIO_BASE 0x{:08X}
#define MMIO_SIZE 0x{:08X}

static int major_number;
static void __iomem *mmio_ptr;

static int __init gooney_init(void) {{
    printk(KERN_INFO "r0-driver: Initializing soft-IP driver for %s\n", "{}");
    
    // Map MMIO region
    if (!request_mem_region(MMIO_BASE, MMIO_SIZE, DEVICE_NAME)) {{
        printk(KERN_ERR "r0-driver: Failed to reserve MMIO region\n");
        return -EBUSY;
    }}

    mmio_ptr = ioremap(MMIO_BASE, MMIO_SIZE);
    if (!mmio_ptr) {{
        printk(KERN_ERR "r0-driver: Failed to ioremap MMIO region\n");
        release_mem_region(MMIO_BASE, MMIO_SIZE);
        return -ENOMEM;
    }}

    printk(KERN_INFO "r0-driver: MMIO successfully mapped at %p\n", mmio_ptr);
    return 0;
}}

static void __exit gooney_exit(void) {{
    if (mmio_ptr) {{
        iounmap(mmio_ptr);
    }}
    release_mem_region(MMIO_BASE, MMIO_SIZE);
    printk(KERN_INFO "r0-driver: Unloaded soft-IP driver\n");
}}

module_init(gooney_init);
module_exit(gooney_exit);
"#,
            config.ip_name,
            config.mmio_base_address,
            config.mmio_size,
            config.ip_name
        );

        let makefile_content = format!(
            r#"obj-m += gooney_drv.o
all:
	make -C /lib/modules/$(shell uname -r)/build M=$(PWD) modules
clean:
	make -C /lib/modules/$(shell uname -r)/build M=$(PWD) clean
"#,
        );

        fs::write(output_dir.join("gooney_drv.c"), c_source)?;
        fs::write(output_dir.join("Makefile"), makefile_content)?;

        Ok(())
    }
}
